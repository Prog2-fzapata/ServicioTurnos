-- Proceso de reserva de un turno. El registro se crea en HOLD_REQUESTED antes de llamar a la cátedra, por eso
-- reservation_process_id y hold_id (ids de la cátedra) aceptan NULL hasta que el hold responde. El UNIQUE
-- sigue evitando duplicados porque PostgreSQL permite varios NULL en una columna única.
-- user_id, professional_id y los nombres del profesional se guardan por valor, sin clave foránea: son datos
-- históricos para mostrar la reserva y viven en otro servicio.
CREATE TABLE reservation_processes (
    id                      BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_process_id  VARCHAR(100),
    hold_id                 VARCHAR(100),
    user_id                 VARCHAR(100) NOT NULL,
    professional_id         BIGINT       NOT NULL,
    professional_first_name VARCHAR(255) NOT NULL,
    professional_last_name  VARCHAR(255) NOT NULL,
    appointment_date        DATE         NOT NULL,
    -- Horas locales de atención, sin zona horaria
    start_time              TIME         NOT NULL,
    end_time                TIME         NOT NULL,
    status                  VARCHAR(15)  NOT NULL,
    expires_at              TIMESTAMPTZ,
    patient_first_name      VARCHAR(100) NOT NULL,
    patient_last_name       VARCHAR(100) NOT NULL,
    patient_phone           VARCHAR(20),
    request_event_id        VARCHAR(100),
    reservation_id          BIGINT,
    failure_reason          TEXT,
    cancellation_reason     VARCHAR(500),
    cancelled_at            TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,
    -- Bloqueo optimista: evita que REST y Kafka pisen el mismo proceso a la vez
    version                 BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_reservation_processes_process_id UNIQUE (reservation_process_id),
    CONSTRAINT ck_reservation_processes_status CHECK (status IN ('HOLD_REQUESTED', 'HELD', 'WAITING_PHONE',
        'PHONE_QUEUED', 'PHONE_SUBMITTED', 'CONFIRMED', 'EXPIRED', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_reservation_processes_time_range CHECK (end_time > start_time)
);

-- Toda consulta y cancelación filtra por el dueño de la reserva
CREATE INDEX idx_reservation_processes_user_id ON reservation_processes (user_id);

-- Recuperación al arrancar y vencimiento: procesos no finales con expires_at vencido
CREATE INDEX idx_reservation_processes_status_expires_at ON reservation_processes (status, expires_at);

-- Outbox: el cambio de estado y el mensaje a publicar se guardan en la misma transacción; un relay publica
-- las filas PENDING y las marca SENT. message_key es el reservationProcessId, como exige la cátedra.
CREATE TABLE outbox_events (
    id                     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id               VARCHAR(255) NOT NULL,
    reservation_process_id VARCHAR(100) NOT NULL,
    topic                  VARCHAR(255) NOT NULL,
    message_key            VARCHAR(100) NOT NULL,
    payload                TEXT         NOT NULL,
    status                 VARCHAR(7)   NOT NULL DEFAULT 'PENDING',
    attempts               INTEGER      NOT NULL DEFAULT 0,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    sent_at                TIMESTAMPTZ,
    CONSTRAINT uk_outbox_events_event_id UNIQUE (event_id),
    CONSTRAINT fk_outbox_events_process FOREIGN KEY (reservation_process_id)
        REFERENCES reservation_processes (reservation_process_id),
    CONSTRAINT ck_outbox_events_status CHECK (status IN ('PENDING', 'SENT'))
);

-- PostgreSQL no indexa las claves foráneas por su cuenta
CREATE INDEX idx_outbox_events_process_id ON outbox_events (reservation_process_id);

-- Parcial: el relay solo lee las pendientes, y las ya enviadas (la mayoría con el tiempo) no pesan en el índice
CREATE INDEX idx_outbox_events_pending ON outbox_events (created_at) WHERE status = 'PENDING';

-- Deduplicación de los eventos de Kafka: se guarda el eventId en la misma transacción que aplica el efecto
CREATE TABLE processed_events (
    event_id     VARCHAR(255) PRIMARY KEY,
    event_type   VARCHAR(100) NOT NULL,
    processed_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
